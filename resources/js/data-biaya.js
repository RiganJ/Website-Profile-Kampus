// Helper Currency Formatter
function formatRupiah(num) {
  if (typeof num !== 'number') {
    num = parseInt(num, 10) || 0;
  }
  return new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0
  }).format(num);
}
